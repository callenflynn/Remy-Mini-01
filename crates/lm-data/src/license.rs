//! Source metadata and license validation. Only allowlisted licenses are accepted; unknown,
//! missing, or copyleft licenses are rejected with an error naming the source.

use anyhow::{Result, bail};
use serde::{Deserialize, Serialize};

/// Licenses accepted for any text that is read from a file.
///
/// `No-License-Granted` is the honest label for locally collected text that carries no
/// license at all (chat-log dumps, transcripts). It is allowed so such material can be
/// declared and attributed instead of silently included; it carries no redistribution rights,
/// so anything trained on it is for local use. Attribution for every entry belongs in the
/// data README.
pub const ALLOWED_LICENSES: &[&str] = &[
    "CC0-1.0",
    "Public-Domain",
    "Unlicense",
    "MIT",
    "ISC",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "Apache-2.0",
    "CC-BY-4.0",
    "CC-BY-SA-4.0",
    "CC-BY-NC-SA-4.0",
    "No-License-Granted",
];

/// Where a source's text came from. Synthetic text is generated internally and is never a
/// configured source, so `Synthetic` is rejected by `SourceMeta::validate`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum SourceKind {
    /// Small, project-authored test material.
    Fixture,
    /// Text obtained from outside the project.
    External,
    /// Generated by this crate. Not allowed in configuration.
    Synthetic,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SourceMeta {
    pub name: String,
    pub kind: SourceKind,
    #[serde(default)]
    pub origin: String,
    #[serde(default)]
    pub license: String,
    /// Preprocessing history, recorded in the manifest.
    #[serde(default)]
    pub preprocessing: Vec<String>,
}

impl SourceMeta {
    pub fn validate(&self) -> Result<()> {
        if self.name.trim().is_empty() {
            bail!("source name must not be empty");
        }
        if self.kind == SourceKind::Synthetic {
            bail!(
                "source '{}': synthetic data is generated internally and cannot be declared as a source",
                self.name
            );
        }
        if self.origin.trim().is_empty() {
            bail!(
                "source '{}': origin must say where the text came from",
                self.name
            );
        }
        if self.license.trim().is_empty() {
            bail!(
                "source '{}': license metadata is missing; set one of {:?}",
                self.name,
                ALLOWED_LICENSES
            );
        }
        if !ALLOWED_LICENSES.contains(&self.license.as_str()) {
            bail!(
                "source '{}': license '{}' is not on the allowlist {:?}",
                self.name,
                self.license,
                ALLOWED_LICENSES
            );
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn meta(license: &str) -> SourceMeta {
        SourceMeta {
            name: "s".into(),
            kind: SourceKind::External,
            origin: "https://example.org/corpus".into(),
            license: license.into(),
            preprocessing: vec![],
        }
    }

    #[test]
    fn allowlisted_license_accepted() {
        meta("CC0-1.0").validate().unwrap();
        meta("Public-Domain").validate().unwrap();
    }

    #[test]
    fn share_alike_and_unlicensed_collections_accepted() {
        // Attribution-bearing licenses and local-only collections are declared, not hidden.
        meta("CC-BY-SA-4.0").validate().unwrap();
        meta("CC-BY-NC-SA-4.0").validate().unwrap();
        meta("No-License-Granted").validate().unwrap();
    }

    #[test]
    fn missing_unknown_and_gpl_licenses_rejected() {
        for bad in ["", "   ", "Proprietary", "GPL-3.0", "cc-by-sa-4.0"] {
            let err = meta(bad).validate().unwrap_err().to_string();
            assert!(err.contains("s"), "{err}");
        }
    }

    #[test]
    fn missing_origin_rejected() {
        let mut m = meta("MIT");
        m.origin = " ".into();
        assert!(m.validate().is_err());
    }

    #[test]
    fn synthetic_cannot_be_declared() {
        let mut m = meta("MIT");
        m.kind = SourceKind::Synthetic;
        let err = m.validate().unwrap_err().to_string();
        assert!(err.contains("synthetic"), "{err}");
    }
}
